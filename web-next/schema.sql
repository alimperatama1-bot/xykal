CREATE TABLE IF NOT EXISTS rate_limits (key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS settings (repo TEXT PRIMARY KEY, inputs TEXT NOT NULL, updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS devices (id TEXT PRIMARY KEY, token_hash TEXT UNIQUE NOT NULL, subject TEXT NOT NULL, name TEXT NOT NULL, payload TEXT NOT NULL, expires INTEGER NOT NULL, created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS locks (key TEXT PRIMARY KEY, expires INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS repositories(subject TEXT PRIMARY KEY, repo TEXT NOT NULL, state TEXT NOT NULL, updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS credentials(repo TEXT PRIMARY KEY, payload TEXT NOT NULL, remote_updated TEXT NOT NULL, updated INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS app_config(name TEXT PRIMARY KEY,payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS app_installations(subject TEXT PRIMARY KEY,installation_id INTEGER NOT NULL,account_id TEXT NOT NULL,login TEXT NOT NULL,updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS app_states(hash TEXT PRIMARY KEY,subject TEXT NOT NULL,kind TEXT NOT NULL,expires INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS community_members (
 subject TEXT PRIMARY KEY,
 github_id TEXT UNIQUE NOT NULL,
 login TEXT NOT NULL,
 joined_at INTEGER NOT NULL,
 last_seen INTEGER NOT NULL DEFAULT 0,
 show_profile INTEGER NOT NULL DEFAULT 0 CHECK(show_profile IN (0,1))
);
CREATE INDEX IF NOT EXISTS community_members_seen ON community_members(last_seen);
CREATE INDEX IF NOT EXISTS community_members_public ON community_members(show_profile,joined_at);
